import os
from contextlib import contextmanager
from datetime import datetime, timezone

import psycopg
from psycopg.rows import dict_row


def database_url():
    url = os.environ.get('DATABASE_URL', '').strip()
    if not url:
        raise RuntimeError(
            'DATABASE_URL is not set. Example: '
            'postgresql://chess:chess@localhost:5432/chess_assistant'
        )
    # Render/Heroku sometimes use postgres://
    if url.startswith('postgres://'):
        url = 'postgresql://' + url[len('postgres://'):]
    return url


@contextmanager
def get_connection():
    conn = psycopg.connect(database_url(), row_factory=dict_row)
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db():
    with get_connection() as conn:
        conn.execute(
            '''
            CREATE TABLE IF NOT EXISTS games (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                history TEXT NOT NULL DEFAULT '',
                user_color TEXT NOT NULL DEFAULT 'w',
                start_fen TEXT NOT NULL,
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL
            )
            '''
        )


def _now():
    return datetime.now(timezone.utc).isoformat(timespec='seconds')


def list_games():
    with get_connection() as conn:
        rows = conn.execute(
            '''
            SELECT id, name, history, user_color, start_fen, created_at, updated_at
            FROM games
            ORDER BY updated_at DESC, id DESC
            '''
        ).fetchall()
    return [dict(row) for row in rows]


def get_game(game_id):
    with get_connection() as conn:
        row = conn.execute(
            '''
            SELECT id, name, history, user_color, start_fen, created_at, updated_at
            FROM games
            WHERE id = %s
            ''',
            (game_id,),
        ).fetchone()
    return dict(row) if row else None


def create_game(name, history, user_color, start_fen):
    now = _now()
    with get_connection() as conn:
        row = conn.execute(
            '''
            INSERT INTO games (name, history, user_color, start_fen, created_at, updated_at)
            VALUES (%s, %s, %s, %s, %s, %s)
            RETURNING id
            ''',
            (name, history or '', user_color, start_fen, now, now),
        ).fetchone()
    return row['id']


def update_game_history(game_id, history):
    with get_connection() as conn:
        conn.execute(
            '''
            UPDATE games
            SET history = %s, updated_at = %s
            WHERE id = %s
            ''',
            (history or '', _now(), game_id),
        )


def delete_game(game_id):
    with get_connection() as conn:
        cur = conn.execute('DELETE FROM games WHERE id = %s', (game_id,))
        return cur.rowcount > 0


def upsert_game(game_id, name, history, user_color, start_fen, created_at, updated_at):
    """Insert or replace a game with an explicit id (used by migration)."""
    with get_connection() as conn:
        conn.execute(
            '''
            INSERT INTO games (id, name, history, user_color, start_fen, created_at, updated_at)
            VALUES (%s, %s, %s, %s, %s, %s, %s)
            ON CONFLICT (id) DO UPDATE SET
                name = EXCLUDED.name,
                history = EXCLUDED.history,
                user_color = EXCLUDED.user_color,
                start_fen = EXCLUDED.start_fen,
                created_at = EXCLUDED.created_at,
                updated_at = EXCLUDED.updated_at
            ''',
            (game_id, name, history or '', user_color, start_fen, created_at, updated_at),
        )
        conn.execute(
            '''
            SELECT setval(
                pg_get_serial_sequence('games', 'id'),
                GREATEST((SELECT COALESCE(MAX(id), 1) FROM games), 1)
            )
            '''
        )
