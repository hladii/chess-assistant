def puzzle_stats_for_user(user_id):
    with get_connection() as conn:
        totals = conn.execute(
            '''
            SELECT
                (SELECT COUNT(*) FROM puzzles WHERE active = TRUE) AS catalog_total,
                (
                    SELECT COUNT(DISTINCT puzzle_id)
                    FROM puzzle_attempts
                    WHERE user_id = %s AND status = 'solved'
                ) AS solved_puzzles,
                (
                    SELECT COUNT(*)
                    FROM puzzle_attempts
                    WHERE user_id = %s AND status IN ('solved', 'failed')
                ) AS finished_attempts,
                (
                    SELECT COUNT(*)
                    FROM puzzle_attempts
                    WHERE user_id = %s AND status = 'solved'
                ) AS solved_attempts,
                (
                    SELECT MAX(COALESCE(finished_at, created_at))
                    FROM puzzle_attempts
                    WHERE user_id = %s AND status IN ('solved', 'failed')
                ) AS last_activity
            ''',
            (user_id, user_id, user_id, user_id),
        ).fetchone()
        recent = conn.execute(
            '''
            SELECT status
            FROM puzzle_attempts
            WHERE user_id = %s AND status IN ('solved', 'failed')
            ORDER BY COALESCE(finished_at, created_at) DESC, id DESC
            LIMIT 100
            ''',
            (user_id,),
        ).fetchall()

    finished = int(totals['finished_attempts'] or 0)
    solved_attempts = int(totals['solved_attempts'] or 0)
    success_pct = int(round(100 * solved_attempts / finished)) if finished else None

    # recent is newest-first
    current_streak = 0
    for row in recent:
        if row['status'] == 'solved':
            current_streak += 1
        else:
            break
    best_streak = 0
    run = 0
    for row in reversed(list(recent)):
        if row['status'] == 'solved':
            run += 1
            best_streak = max(best_streak, run)
        else:
            run = 0

    return {
        'catalog_total': int(totals['catalog_total'] or 0),
        'solved_puzzles': int(totals['solved_puzzles'] or 0),
        'finished_attempts': finished,
        'solved_attempts': solved_attempts,
        'success_pct': success_pct,
        'current_streak': current_streak,
        'best_streak': best_streak,
        'last_activity': totals['last_activity'],
    }


