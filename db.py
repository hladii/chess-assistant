def search_users(query, exclude_id, limit=10):
    """Search users by name/email. Empty query → first `limit` others (default list)."""
    q = (query or '').strip()
    with get_connection() as conn:
        if not q:
            rows = conn.execute(
                '''
                SELECT id, email, display_name, elo_rating
                FROM users
                WHERE id <> %s
                ORDER BY display_name ASC, email ASC, id ASC
                LIMIT %s
                ''',
                (exclude_id, limit),
            ).fetchall()
        else:
            pattern = f'%{q}%'
            rows = conn.execute(
                '''
                SELECT id, email, display_name, elo_rating
                FROM users
                WHERE id <> %s
                  AND (
                    display_name ILIKE %s
                    OR email ILIKE %s
                  )
                ORDER BY
                  CASE
                    WHEN lower(display_name) = lower(%s) THEN 0
                    WHEN lower(email) = lower(%s) THEN 1
                    WHEN lower(display_name) LIKE lower(%s) THEN 2
                    WHEN lower(email) LIKE lower(%s) THEN 3
                    ELSE 4
                  END,
                  display_name ASC,
                  email ASC
                LIMIT %s
                ''',
                (
                    exclude_id,
                    pattern,
                    pattern,
                    q,
                    q,
                    f'{q}%',
                    f'{q}%',
                    limit,
                ),
            ).fetchall()
    return [dict(row) for row in rows]


