import os
from contextlib import contextmanager
from datetime import datetime, timezone

import psycopg
from psycopg.rows import dict_row

from auth import hash_password, normalize_email, seed_credentials


def database_url():
    url = os.environ.get('DATABASE_URL', '').strip()
    if not url:
        raise RuntimeError(
            'DATABASE_URL is not set. Example: '
            'postgresql://chess:chess@localhost:5432/chess_assistant'
        )
    if url.startswith('postgres://'):
        url = 'postgresql://' + url[len('postgres://'):]
    return url


@contextmanager
def get_connection():
    conn = psycopg.connect(database_url(), row_factory=dict_row)
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def _now():
    return datetime.now(timezone.utc).isoformat(timespec='seconds')


def init_db():
    with get_connection() as conn:
        conn.execute(
            '''
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL
            )
            '''
        )
        conn.execute(
            '''
            CREATE TABLE IF NOT EXISTS games (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
                name TEXT NOT NULL,
                history TEXT NOT NULL DEFAULT '',
                user_color TEXT NOT NULL DEFAULT 'w',
                start_fen TEXT NOT NULL,
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL
            )
            '''
        )
        # Upgrade older schemas that had games without user_id.
        conn.execute(
            '''
            DO $$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1 FROM information_schema.columns
                    WHERE table_name = 'games' AND column_name = 'user_id'
                ) THEN
                    ALTER TABLE games ADD COLUMN user_id BIGINT REFERENCES users(id) ON DELETE CASCADE;
                END IF;
            END $$;
            '''
        )

    seed_default_user()


def seed_default_user():
    email, password = seed_credentials()
    existing = get_user_by_email(email)
    if existing:
        assign_orphan_games(existing['id'])
        return existing['id']

    user_id = create_user(email, password)
    assign_orphan_games(user_id)
    return user_id


def create_user(email, password):
    now = _now()
    email = normalize_email(email)
    with get_connection() as conn:
        row = conn.execute(
            '''
            INSERT INTO users (email, password_hash, created_at, updated_at)
            VALUES (%s, %s, %s, %s)
            RETURNING id
            ''',
            (email, hash_password(password), now, now),
        ).fetchone()
    return row['id']


def get_user_by_email(email):
    email = normalize_email(email)
    with get_connection() as conn:
        row = conn.execute(
            '''
            SELECT id, email, password_hash, created_at, updated_at
            FROM users
            WHERE email = %s
            ''',
            (email,),
        ).fetchone()
    return dict(row) if row else None


def get_user_by_id(user_id):
    with get_connection() as conn:
        row = conn.execute(
            '''
            SELECT id, email, password_hash, created_at, updated_at
            FROM users
            WHERE id = %s
            ''',
            (user_id,),
        ).fetchone()
    return dict(row) if row else None


def update_user_password(user_id, new_password):
    with get_connection() as conn:
        cur = conn.execute(
            '''
            UPDATE users
            SET password_hash = %s, updated_at = %s
            WHERE id = %s
            ''',
            (hash_password(new_password), _now(), user_id),
        )
        return cur.rowcount > 0


def assign_orphan_games(user_id):
    with get_connection() as conn:
        conn.execute(
            '''
            UPDATE games
            SET user_id = %s
            WHERE user_id IS NULL
            ''',
            (user_id,),
        )


def list_games(user_id):
    with get_connection() as conn:
        rows = conn.execute(
            '''
            SELECT id, user_id, name, history, user_color, start_fen, created_at, updated_at
            FROM games
            WHERE user_id = %s
            ORDER BY updated_at DESC, id DESC
            ''',
            (user_id,),
        ).fetchall()
    return [dict(row) for row in rows]


def get_game_for_user(game_id, user_id):
    with get_connection() as conn:
        row = conn.execute(
            '''
            SELECT id, user_id, name, history, user_color, start_fen, created_at, updated_at
            FROM games
            WHERE id = %s AND user_id = %s
            ''',
            (game_id, user_id),
        ).fetchone()
    return dict(row) if row else None


def create_game(user_id, name, history, user_color, start_fen):
    now = _now()
    with get_connection() as conn:
        row = conn.execute(
            '''
            INSERT INTO games (user_id, name, history, user_color, start_fen, created_at, updated_at)
            VALUES (%s, %s, %s, %s, %s, %s, %s)
            RETURNING id
            ''',
            (user_id, name, history or '', user_color, start_fen, now, now),
        ).fetchone()
    return row['id']


def update_game_history(game_id, user_id, history):
    with get_connection() as conn:
        cur = conn.execute(
            '''
            UPDATE games
            SET history = %s, updated_at = %s
            WHERE id = %s AND user_id = %s
            ''',
            (history or '', _now(), game_id, user_id),
        )
        return cur.rowcount > 0


def delete_game(game_id, user_id):
    with get_connection() as conn:
        cur = conn.execute(
            'DELETE FROM games WHERE id = %s AND user_id = %s',
            (game_id, user_id),
        )
        return cur.rowcount > 0


def upsert_game(game_id, name, history, user_color, start_fen, created_at, updated_at, user_id=None):
    """Insert or replace a game with an explicit id (used by migration)."""
    if user_id is None:
        email, _ = seed_credentials()
        user = get_user_by_email(email)
        if not user:
            user_id = seed_default_user()
        else:
            user_id = user['id']

    with get_connection() as conn:
        conn.execute(
            '''
            INSERT INTO games (id, user_id, name, history, user_color, start_fen, created_at, updated_at)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
            ON CONFLICT (id) DO UPDATE SET
                user_id = EXCLUDED.user_id,
                name = EXCLUDED.name,
                history = EXCLUDED.history,
                user_color = EXCLUDED.user_color,
                start_fen = EXCLUDED.start_fen,
                created_at = EXCLUDED.created_at,
                updated_at = EXCLUDED.updated_at
            ''',
            (
                game_id,
                user_id,
                name,
                history or '',
                user_color,
                start_fen,
                created_at,
                updated_at,
            ),
        )
        conn.execute(
            '''
            SELECT setval(
                pg_get_serial_sequence('games', 'id'),
                GREATEST((SELECT COALESCE(MAX(id), 1) FROM games), 1)
            )
            '''
        )
