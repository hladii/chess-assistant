import json
import os
from contextlib import contextmanager
from datetime import datetime, timezone

import psycopg
from psycopg.rows import dict_row

from auth import (
    hash_password,
    normalize_display_name,
    normalize_email,
    seed_credentials,
)


def database_url():
    url = os.environ.get('DATABASE_URL', '').strip()
    if not url:
        raise RuntimeError(
            'DATABASE_URL is not set. Example: '
            'postgresql://chess:chess@localhost:5432/chess_assistant'
        )
    if url.startswith('postgres://'):
        url = 'postgresql://' + url[len('postgres://'):]
    return url


@contextmanager
def get_connection():
    conn = psycopg.connect(database_url(), row_factory=dict_row)
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def _now():
    return datetime.now(timezone.utc).isoformat(timespec='seconds')


def init_db():
    with get_connection() as conn:
        conn.execute(
            '''
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                display_name TEXT NOT NULL DEFAULT '',
                locale TEXT NOT NULL DEFAULT 'en',
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL
            )
            '''
        )
        conn.execute(
            '''
            CREATE TABLE IF NOT EXISTS games (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
                name TEXT NOT NULL,
                history TEXT NOT NULL DEFAULT '',
                user_color TEXT NOT NULL DEFAULT 'w',
                start_fen TEXT NOT NULL,
                mode TEXT NOT NULL DEFAULT 'assistant',
                trainer_elo INT,
                quality_scores TEXT NOT NULL DEFAULT '[]',
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL
            )
            '''
        )
        # Upgrade older schemas.
        conn.execute(
            '''
            DO $$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1 FROM information_schema.columns
                    WHERE table_name = 'games' AND column_name = 'user_id'
                ) THEN
                    ALTER TABLE games ADD COLUMN user_id BIGINT REFERENCES users(id) ON DELETE CASCADE;
                END IF;
                IF NOT EXISTS (
                    SELECT 1 FROM information_schema.columns
                    WHERE table_name = 'games' AND column_name = 'mode'
                ) THEN
                    ALTER TABLE games ADD COLUMN mode TEXT NOT NULL DEFAULT 'assistant';
                END IF;
                IF NOT EXISTS (
                    SELECT 1 FROM information_schema.columns
                    WHERE table_name = 'games' AND column_name = 'trainer_elo'
                ) THEN
                    ALTER TABLE games ADD COLUMN trainer_elo INT;
                END IF;
                IF NOT EXISTS (
                    SELECT 1 FROM information_schema.columns
                    WHERE table_name = 'games' AND column_name = 'quality_scores'
                ) THEN
                    ALTER TABLE games ADD COLUMN quality_scores TEXT NOT NULL DEFAULT '[]';
                END IF;
                IF NOT EXISTS (
                    SELECT 1 FROM information_schema.columns
                    WHERE table_name = 'users' AND column_name = 'display_name'
                ) THEN
                    ALTER TABLE users ADD COLUMN display_name TEXT NOT NULL DEFAULT '';
                END IF;
                IF NOT EXISTS (
                    SELECT 1 FROM information_schema.columns
                    WHERE table_name = 'users' AND column_name = 'locale'
                ) THEN
                    ALTER TABLE users ADD COLUMN locale TEXT NOT NULL DEFAULT 'en';
                END IF;
            END $$;
            '''
        )

    seed_default_user()


def seed_default_user():
    email, password, name = seed_credentials()
    existing = get_user_by_email(email)
    if existing:
        if not (existing.get('display_name') or '').strip():
            update_user_profile(existing['id'], name)
        assign_orphan_games(existing['id'])
        return existing['id']

    user_id = create_user(email, password, name)
    assign_orphan_games(user_id)
    return user_id


def create_user(email, password, display_name=''):
    now = _now()
    email = normalize_email(email)
    display_name = normalize_display_name(display_name)
    with get_connection() as conn:
        row = conn.execute(
            '''
            INSERT INTO users (email, password_hash, display_name, created_at, updated_at)
            VALUES (%s, %s, %s, %s, %s)
            RETURNING id
            ''',
            (email, hash_password(password), display_name, now, now),
        ).fetchone()
    return row['id']


def get_user_by_email(email):
    email = normalize_email(email)
    with get_connection() as conn:
        row = conn.execute(
            '''
            SELECT id, email, password_hash, display_name, locale, created_at, updated_at
            FROM users
            WHERE email = %s
            ''',
            (email,),
        ).fetchone()
    return dict(row) if row else None


def get_user_by_id(user_id):
    with get_connection() as conn:
        row = conn.execute(
            '''
            SELECT id, email, password_hash, display_name, locale, created_at, updated_at
            FROM users
            WHERE id = %s
            ''',
            (user_id,),
        ).fetchone()
