def update_user_locale(user_id, locale):
    locale = (locale or 'en').strip().lower()
    if locale not in ('uk', 'en', 'it'):
        locale = 'en'
    with get_connection() as conn:
        cur = conn.execute(
            '''
            UPDATE users
            SET locale = %s, updated_at = %s
            WHERE id = %s
            ''',
            (locale, _now(), user_id),
        )
        return cur.rowcount > 0


def assign_orphan_games(user_id):
    with get_connection() as conn:
        conn.execute(
            '''
            UPDATE games
            SET user_id = %s
            WHERE user_id IS NULL
            ''',
            (user_id,),
        )


def scores_from_game(game):
    raw = (game or {}).get('quality_scores')
    if raw is None or raw == '':
        return []
    if isinstance(raw, list):
        return [int(x) for x in raw]
    try:
        data = json.loads(raw)
    except (TypeError, ValueError, json.JSONDecodeError):
        return []
    if not isinstance(data, list):
        return []
    scores = []
    for item in data:
        try:
            scores.append(int(item))
        except (TypeError, ValueError):
            continue
    return scores


def accuracy_from_scores(scores):
    if not scores:
        return None
    return int(round(sum(scores) / len(scores)))


def _write_quality_scores(game_id, user_id, scores):
    payload = json.dumps(scores)
    with get_connection() as conn:
        cur = conn.execute(
            '''
            UPDATE games
            SET quality_scores = %s, updated_at = %s
            WHERE id = %s AND user_id = %s
            ''',
            (payload, _now(), game_id, user_id),
        )
        return cur.rowcount > 0


def append_quality_score(game_id, user_id, points):
    game = get_game_for_user(game_id, user_id)
    if not game:
        return False
    scores = scores_from_game(game)
    scores.append(int(points))
    return _write_quality_scores(game_id, user_id, scores)


def pop_quality_score(game_id, user_id):
    game = get_game_for_user(game_id, user_id)
    if not game:
        return False
    scores = scores_from_game(game)
    if not scores:
        return True
    scores.pop()
    return _write_quality_scores(game_id, user_id, scores)


def list_games(user_id):
    with get_connection() as conn:
        rows = conn.execute(
            '''
            SELECT id, user_id, name, history, user_color, start_fen, mode, trainer_elo,
                   quality_scores, created_at, updated_at
            FROM games
            WHERE user_id = %s
            ORDER BY updated_at DESC, id DESC
            ''',
            (user_id,),
        ).fetchall()
    return [dict(row) for row in rows]


def get_game_for_user(game_id, user_id):
    with get_connection() as conn:
        row = conn.execute(
            '''
            SELECT id, user_id, name, history, user_color, start_fen, mode, trainer_elo,
                   quality_scores, created_at, updated_at
            FROM games
            WHERE id = %s AND user_id = %s
            ''',
            (game_id, user_id),
        ).fetchone()
    return dict(row) if row else None


def create_game(user_id, name, history, user_color, start_fen, mode='assistant', trainer_elo=None):
    now = _now()
    mode = mode if mode in ('assistant', 'trainer') else 'assistant'
    if mode != 'trainer':
        trainer_elo = None
    with get_connection() as conn:
        row = conn.execute(
            '''
            INSERT INTO games (
                user_id, name, history, user_color, start_fen, mode, trainer_elo,
                quality_scores, created_at, updated_at
            )
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            RETURNING id
            ''',
            (
                user_id,
                name,
                history or '',
                user_color,
                start_fen,
                mode,
                trainer_elo,
                '[]',
                now,
                now,
            ),
        ).fetchone()
    return row['id']


def update_game_history(game_id, user_id, history):
    with get_connection() as conn:
        cur = conn.execute(
            '''
            UPDATE games
            SET history = %s, updated_at = %s
            WHERE id = %s AND user_id = %s
            ''',
            (history or '', _now(), game_id, user_id),
        )
        return cur.rowcount > 0


def delete_game(game_id, user_id):
    with get_connection() as conn:
        cur = conn.execute(
            'DELETE FROM games WHERE id = %s AND user_id = %s',
            (game_id, user_id),
        )
        return cur.rowcount > 0


def upsert_game(game_id, name, history, user_color, start_fen, created_at, updated_at, user_id=None):
    """Insert or replace a game with an explicit id (used by migration)."""
    if user_id is None:
        email, _, _ = seed_credentials()
        user = get_user_by_email(email)
        if not user:
            user_id = seed_default_user()
        else:
            user_id = user['id']

    with get_connection() as conn:
        conn.execute(
            '''
            INSERT INTO games (id, user_id, name, history, user_color, start_fen, created_at, updated_at)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
            ON CONFLICT (id) DO UPDATE SET
                user_id = EXCLUDED.user_id,
                name = EXCLUDED.name,
                history = EXCLUDED.history,
                user_color = EXCLUDED.user_color,
                start_fen = EXCLUDED.start_fen,
                created_at = EXCLUDED.created_at,
                updated_at = EXCLUDED.updated_at
            ''',
            (
                game_id,
                user_id,
                name,
                history or '',
                user_color,
                start_fen,
                created_at,
                updated_at,
            ),
        )
        conn.execute(
            '''
            SELECT setval(
                pg_get_serial_sequence('games', 'id'),
                GREATEST((SELECT COALESCE(MAX(id), 1) FROM games), 1)
            )
            '''
        )
