def update_puzzle_attempt(attempt_id, user_id, *, status=None, moves_played=None,
                          ply_index=None, finished=False, duration_ms=None):
    fields = []
    values = []
    if status is not None:
        fields.append('status = %s')
        values.append(status)
    if moves_played is not None:
        fields.append('moves_played = %s')
        values.append(json.dumps(moves_played))
    if ply_index is not None:
        fields.append('ply_index = %s')
        values.append(int(ply_index))
    if duration_ms is not None:
        fields.append('duration_ms = %s')
        values.append(int(duration_ms))
    if finished:
        fields.append('finished_at = %s')
        values.append(_now())
    if not fields:
        return False
    values.extend([attempt_id, user_id])
    with get_connection() as conn:
        cur = conn.execute(
            f'''
            UPDATE puzzle_attempts
            SET {', '.join(fields)}
            WHERE id = %s AND user_id = %s
            ''',
            tuple(values),
        )
        return cur.rowcount > 0


